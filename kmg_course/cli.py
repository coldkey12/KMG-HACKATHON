"""Command line: python -m kmg_course <command> ...

  build <layer.json> [--out DIR] [--no-tasks]
      layer -> demo course folder (default: <layer dir>/course/), opens locally without a server.
      Tasks are generated by the model on the first run, then served from cache (cost $0) on rebuilds.
"""
import argparse
import json
import re
import shutil
import sys
import time
from pathlib import Path
from xml.sax.saxutils import escape

from kmg.config import ROOT, domain_pack

from . import illus, model, tasks as tasks_mod

STATIC = Path(__file__).resolve().parent / "static"
MAX_MB = 30
APP_FILES = ("app.js", "style.css")


def _media(layer_path):
    """Media built by `kmg_course video` for this chapter: <layer dir>/media/<node>/manifest.json.
    Frame class and provenance label are read from the video passport when it has them."""
    media_src = layer_path.parent / "media"
    media = {}
    if media_src.exists():
        for mf in sorted(media_src.glob("*/manifest.json")):
            m = dict(json.loads(mf.read_text(encoding="utf-8")), dir=mf.parent.name)
            if not m.get("mp4") or not (mf.parent / m["mp4"]).exists():
                continue  # no video file -> nothing to put on the step (the page must not break)
            pj = mf.parent / "passport.json"
            if pj.exists():
                try:
                    p = json.loads(pj.read_text(encoding="utf-8"))
                    spec = p.get("scene_spec") or {}
                    frames = p.get("frames") or []
                    m["frame_class"] = p.get("frame_class") or spec.get("frame_class") or (frames[0].get("class") if frames else None)
                    prov = " ".join(str(f.get("provenance", "")) for f in frames[:1]).lower()
                    m["label"] = next((l for l in ("реальные данные", "симуляция", "схема") if prov.startswith(l[:5])), None)
                    m["claim_ids"] = sorted({c for s in (p.get("sources") or []) if isinstance(s, dict)
                                             for c in ([s.get("claim_id")] if s.get("claim_id") else s.get("claim_ids", []))})
                except (ValueError, AttributeError, TypeError):
                    pass
            media.setdefault(m["node_id"], []).append(m)
    return media_src, media


def _inline_md(s):
    s = escape(s)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", s)
    return s


def md_html(md, title):
    """Minimal Markdown -> standalone HTML (headings, pipe tables, lists, paragraphs) so the video passport opens as
    a readable page from the course, offline."""
    out, para, i = [], [], 0
    lines = md.splitlines()

    def flush():
        if para:
            out.append("<p>%s</p>" % _inline_md(" ".join(para)))
            del para[:]
    while i < len(lines):
        ln = lines[i].rstrip()
        if ln.startswith("|"):
            flush()
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c):
                    rows.append(cells)
                i += 1
            html = "".join("<tr>%s</tr>" % "".join("<%s>%s</%s>" % ("th" if r == 0 else "td", _inline_md(c), "th" if r == 0 else "td")
                                                   for c in row) for r, row in enumerate(rows))
            out.append('<div class="tw"><table>%s</table></div>' % html)
            continue
        m = re.match(r"(#{1,4})\s+(.*)", ln)
        if m:
            flush()
            out.append("<h%d>%s</h%d>" % (len(m.group(1)), _inline_md(m.group(2)), len(m.group(1))))
        elif re.match(r"\s*[-*]\s+", ln):
            flush()
            items = []
            while i < len(lines) and re.match(r"\s*[-*]\s+", lines[i]):
                items.append("<li>%s</li>" % _inline_md(re.sub(r"^\s*[-*]\s+", "", lines[i])))
                i += 1
            out.append("<ul>%s</ul>" % "".join(items))
            continue
        elif not ln.strip():
            flush()
        else:
            para.append(ln.strip())
        i += 1
    flush()
    css = ("body{font:17px/1.6 system-ui,-apple-system,'Segoe UI',Roboto,sans-serif;max-width:980px;margin:0 auto;padding:16px;"
           "color:#1B1F24;background:#fff}@media(prefers-color-scheme:dark){body{color:#E6E9EE;background:#0F1216}th{background:#242A33!important}}"
           ".tw{overflow-x:auto}table{border-collapse:collapse;font-size:16px}th,td{border:1px solid #8A939F;padding:4px 8px;text-align:left;vertical-align:top}"
           "th{background:#EBEEF2}code{font-size:16px}a{color:#3B4CCA}")
    return ('<!doctype html><html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            "<title>%s</title><style>%s</style></head><body><p><a href=\"javascript:history.back()\">← Назад к курсу</a></p>%s</body></html>"
            % (escape(title), css, "\n".join(out)))


def _write_app(out, title):
    (out / "assets").mkdir(parents=True, exist_ok=True)
    for f in APP_FILES:
        shutil.copy(STATIC / f, out / "assets" / f)
    html = (STATIC / "index.html").read_text(encoding="utf-8").replace("{{TITLE}}", escape(title))
    (out / "index.html").write_text(html, encoding="utf-8")


def _decor(view, pack, out):
    """Photos (domain pack, class D) and the styleguide legend: copied into the course, attached to the view.
    Returns the illustration records of the photos (organizers' format)."""
    shutil.rmtree(out / "assets" / "photos", ignore_errors=True)
    style = illus.load_style(pack)
    view["style"] = {"school": style.get("school"), "source": style.get("source"), "provenance": style.get("provenance") or {},
                     "groups": [{"id": g, "title": t, "items": [{"key": k, "ru": e.get("ru") or k, "color": e["color"]}
                                                                for k, e in (style.get(g) or {}).items()]}
                                for g, t in illus.GROUPS if style.get(g)]}
    pdir, photos = illus.load_photos(pack)
    plan = illus.assign_photos(photos, view["parts"], view["steps"], view["chapter"]["id"])
    recs, pub = [], {"cover": None, "parts": {}, "final": None}
    used = {}

    def put(p):
        small = p.get("file_small") if p.get("file_small") and (pdir / p["file_small"]).exists() else None
        if p["file"] not in used:
            (out / "assets" / "photos").mkdir(parents=True, exist_ok=True)
            for f in filter(None, (p["file"], small)):
                shutil.copy(pdir / f, out / "assets" / "photos" / f)
            used[p["file"]] = "assets/photos/" + p["file"]
        return illus.photo_public(p, used[p["file"]], "assets/photos/" + small if small else None)

    first_of = {}
    for s in view["steps"]:
        first_of.setdefault(s["part"], s["id"])
    if plan["cover"]:
        pub["cover"] = put(plan["cover"])
        recs.append(("course-cover", view["steps"][0]["id"], plan["cover"]))
    for pid, p in plan["parts"].items():
        pub["parts"][pid] = put(p)
        recs.append(("part-cover-" + pid, first_of.get(pid), p))
    if plan["final"]:
        pub["final"] = put(plan["final"])
    view["photos"] = pub
    return [{"id": "%s.photo.%s" % (view["chapter"]["id"], rid), "step_id": sid, "node_id": None,
             "file": used[p["file"]], "frame_class": "D", "origin": "photo", "label": None,
             "caption": p.get("caption_ru") or "", "alt": p.get("alt_ru") or p.get("caption_ru") or "",
             "source": "%s, %s, %s (%s)" % (p["author"], p["license"], p.get("source") or "", p["source_url"]),
             "claim_ids": [], "placement": rid} for rid, sid, p in recs if sid]


def _illustrations_doc(view, out, photo_recs):
    shutil.rmtree(out / "illus", ignore_errors=True)
    (out / "illus").mkdir(parents=True, exist_ok=True)
    items = []
    for s in view["steps"]:
        for r in s["illustrations"]:
            (out / r["file"]).write_text('<?xml version="1.0" encoding="UTF-8"?>\n' + r["svg"], encoding="utf-8")
            items.append({k: v for k, v in r.items() if k not in ("svg", "spec")})
            del r["svg"]
        items += illus.media_items(s)
    items += photo_recs
    for it in items:
        if it.get("label") is None:
            it.pop("label", None)
    return {"chapter": view["chapter"]["id"], "schema": "glava-kurs/illustration.schema.json", "illustrations": items}


def build(layer_path, out=None, with_tasks=True, reuse_tasks=False):
    t0 = time.time()
    layer_path = Path(layer_path)
    layer = json.loads(layer_path.read_text(encoding="utf-8"))
    pack = domain_pack(layer["chapter"]["domain_pack"])
    out = Path(out) if out else layer_path.parent / "course"
    chapter_id = layer["chapter"]["id"]
    log_path = ROOT / "runs" / chapter_id / "course_llm_calls.jsonl"

    view = model.build_view(layer, pack)
    media_src, media = _media(layer_path)
    style = illus.load_style(pack)
    for s in view["steps"]:
        s["media"] = media.get(s["id"], [])
        s["illustrations"] = illus.illustrations(s, style)

    report = {"tasks": None}
    task_list = []
    if with_tasks:
        changed = ()
        if reuse_tasks and (out / "data" / "course.js").exists():   # nodes whose facts differ from the previous build
            try:
                old = json.loads((out / "data" / "course.js").read_text(encoding="utf-8").split("=", 1)[1].strip().rstrip(";"))
                prev_src = {s["id"]: json.dumps(s["blocks"]["source"], ensure_ascii=False, sort_keys=True) for s in old["steps"]}
                changed = {s["id"] for s in view["steps"] if prev_src.get(s["id"]) != json.dumps(s["blocks"]["source"], ensure_ascii=False, sort_keys=True)}
            except (ValueError, KeyError, IndexError):
                changed = ()
        task_list, rep = tasks_mod.build_tasks(layer, out, log_path, reuse=reuse_tasks, drop_nodes=changed)
        if reuse_tasks:
            rep["changed_nodes_tasks_dropped"] = sorted(changed)
        report["tasks"] = rep
    view["tasks"] = task_list

    if out.exists():
        for sub in ("media", "assets", "data", "illus"):
            shutil.rmtree(out / sub, ignore_errors=True)
    (out / "data").mkdir(parents=True, exist_ok=True)
    _write_app(out, view["chapter"]["title"])
    photo_recs = _decor(view, pack, out)
    for node_id, ms in media.items():
        for m in ms:
            dst = out / "media" / m["dir"]
            dst.mkdir(parents=True, exist_ok=True)
            # only what the course uses: video (subtitles are burnt in), the interactive scene and its voice track;
            # the passport is converted to a readable page
            for k in ("mp4", "scene", "audio"):
                if m.get(k) and (media_src / m["dir"] / m[k]).exists():
                    shutil.copy(media_src / m["dir"] / m[k], dst / m[k])
                elif k == "scene":
                    m["scene"] = None   # no scene file -> the step shows no scene box
            pmd = media_src / m["dir"] / (m.get("passport") or "passport.md")
            if pmd.exists() and pmd.suffix == ".html":   # the video stage already renders the passport page
                shutil.copy(pmd, dst / "passport.html")
                m["passport"] = "passport.html"
            elif pmd.exists() and pmd.suffix == ".md":
                (dst / "passport.html").write_text(md_html(pmd.read_text(encoding="utf-8"), "Паспорт ролика: " + (m.get("title") or "")), encoding="utf-8")
                m["passport"] = "passport.html"
            else:
                m["passport"] = None
            m.pop("subtitles_vtt", None)
            m.pop("subtitles", None)
    idoc = _illustrations_doc(view, out, photo_recs)
    (out / "illustrations.json").write_text(json.dumps(idoc, ensure_ascii=False, indent=1), encoding="utf-8")
    ierr = tasks_mod.schema_errors(idoc, "illustration.schema.json")
    (out / "data" / "course.js").write_text("window.COURSE = " + json.dumps(view, ensure_ascii=False) + ";\n", encoding="utf-8")

    # TZ: «курс без видео — не больше 30 МБ на главу» → video files are not counted
    size_mb = sum(f.stat().st_size for f in out.rglob("*") if f.is_file() and f.suffix != ".mp4") / 1e6
    steps = view["steps"]
    no_illus = [s["id"] for s in steps if not s["illustrations"]]
    parts_ab = {s["part"] for s in steps if any(r["frame_class"] in ("A", "B") for r in s["illustrations"]) or s["media"]}
    report.update({
        "schema": "kmg-course-report/0.2.0", "chapter": chapter_id, "layer": str(layer_path.as_posix()),
        "steps": len(steps), "parts": len(view["parts"]), "size_mb": round(size_mb, 2), "size_ok": size_mb <= MAX_MB,
        "steps_without_illustration": no_illus,
        "parts_without_ab_illustration": [p["id"] for p in view["parts"] if p["id"] not in parts_ab],
        "illustrations": len(idoc["illustrations"]), "photos": sum(1 for r in photo_recs),
        "illustration_schema_errors": ierr, "illustration_schema_ok": not ierr,
        "seconds": round(time.time() - t0, 1),
    })
    (out / "course_report.json").write_text(json.dumps(report, ensure_ascii=False, indent=1), encoding="utf-8")
    return out, report


def refresh_assets(layer_path, out=None):
    """Refresh the app (index.html, assets/) and its decoration from the domain pack (photos, colour legend) of an
    already built course: content, tasks, illustrations and media stay as built. For design changes when the layer
    moved on and tasks must not be regenerated yet. No model calls."""
    layer_path = Path(layer_path)
    out = Path(out) if out else layer_path.parent / "course"
    data = out / "data" / "course.js"
    if not data.exists():
        raise SystemExit("курс ещё не собран: %s (нужна полная сборка build)" % out)
    view = json.loads(data.read_text(encoding="utf-8").split("=", 1)[1].strip().rstrip(";"))
    layer = json.loads(layer_path.read_text(encoding="utf-8"))
    _write_app(out, view["chapter"]["title"])
    _decor(view, domain_pack(layer["chapter"]["domain_pack"]), out)
    view["tasks"] = [tasks_mod.upgrade(t) for t in view.get("tasks", [])]
    data.write_text("window.COURSE = " + json.dumps(view, ensure_ascii=False) + ";\n", encoding="utf-8")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(prog="kmg_course")
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("layer")
    b.add_argument("--out", default=None)
    b.add_argument("--no-tasks", action="store_true")
    b.add_argument("--reuse-tasks", action="store_true", help="без вызова модели: задания прошлой сборки перепроверяются по текущему слою (быстрая пересборка после правки факта)")
    b.add_argument("--assets-only", action="store_true", help="обновить только приложение курса (дизайн), содержание и задания не трогать")
    v = sub.add_parser("video")
    v.add_argument("layer")
    v.add_argument("node_id")
    v.add_argument("--format", choices=["short", "long"], default="short")
    v.add_argument("--template", default=None, help="шаблон сцены; по умолчанию format.scene_template узла")
    v.add_argument("--out", default=None)
    v.add_argument("--new-script", action="store_true", help="переписать сценарий, даже если факты узла не менялись")
    cv = sub.add_parser("coverage")
    cv.add_argument("layers", nargs="+")
    cv.add_argument("--registry", default=str(ROOT / "scenes" / "registry.json"))
    pv = sub.add_parser("preview", help="кадры каждой части сцены без сценария и голоса ($0)")
    pv.add_argument("layer")
    pv.add_argument("node_id")
    pv.add_argument("--format", choices=["short", "long"], default="short")
    pv.add_argument("--template", default=None)
    pv.add_argument("--out", default=None)
    rf = sub.add_parser("refresh", help="после правки факта в слое: пересобрать ролики главы, чьи факты изменились, и курс")
    rf.add_argument("layer")
    rf.add_argument("--all", action="store_true", help="пересобрать все ролики главы (например, после правки шаблона)")
    rf.add_argument("--no-course", action="store_true", help="только ролики, без сборки курса")
    args = ap.parse_args(argv)
    if args.cmd == "refresh":
        from .video import refresh
        res = refresh.run(args.layer, rebuild_all=args.all, course=not args.no_course)
        print(json.dumps(res, ensure_ascii=False))
        return
    if args.cmd == "preview":
        from .video import build as vb
        out, rep = vb.preview(args.layer, args.node_id, args.format, args.template, args.out)
        print(json.dumps({"out": str(out), "template": rep["template"], "shots": len(rep["shots"]), "page_errors": rep["page_errors"],
                          "invariants_ok": all(i["ok"] for i in rep["invariants"]),
                          "failed": [i["id"] for i in rep["invariants"] if not i["ok"]]}, ensure_ascii=False))
        return
    if args.cmd == "coverage":
        from .video import coverage
        coverage.write_registry(args.registry)
        for lp in args.layers:
            res, out = coverage.report(lp)
            print(json.dumps({"chapter": res["chapter"], "video_nodes": res["video_nodes"], "covered": res["covered"],
                              "covered_fallback_only": res.get("covered_fallback"),
                              "report": str(out)}, ensure_ascii=False))
        return
    if args.cmd == "video":
        from .video import build as vb
        out, pj = vb.build(args.layer, args.node_id, args.format, args.template, args.out, new_script=args.new_script)
        m = pj["measurements"]
        print(json.dumps({"out": str(out), "duration_s": pj["duration_s"], "wpm": m["wpm"], "lufs": m["lufs"],
                          "voice": m["voice"], "fallback_used": m["fallback_used"], "script_cost_usd": m["script_cost_usd"],
                          "invariants_ok": all(i["ok"] for i in m["invariants"])}, ensure_ascii=False))
        return
    if args.cmd == "build" and args.assets_only:
        print(json.dumps({"out": str(refresh_assets(args.layer, args.out)), "assets_only": True}, ensure_ascii=False))
        return
    if args.cmd == "build":
        out, rep = build(args.layer, args.out, with_tasks=not args.no_tasks, reuse_tasks=args.reuse_tasks)
        t = rep.get("tasks") or {}
        print(json.dumps({"out": str(out), "steps": rep["steps"], "size_mb": rep["size_mb"],
                          "tasks_kept": t.get("kept"), "tasks_generated": t.get("generated"), "task_types": t.get("types"),
                          "tasks_meet_tz": t.get("meets_tz"), "tasks_schema_ok": t.get("schema_ok"), "cost_usd": t.get("cost_usd"),
                          "illustrations": rep["illustrations"], "illustrations_schema_ok": rep["illustration_schema_ok"],
                          "photos": rep["photos"],
                          "steps_without_illustration": len(rep["steps_without_illustration"])}, ensure_ascii=False))
        problems = []
        if not rep["size_ok"]:
            problems.append("курс без видео весит %.1f МБ > %d МБ" % (rep["size_mb"], MAX_MB))
        if t and not t.get("meets_tz"):
            problems.append("заданий %s, типов %s: нужно ≥15 заданий и ≥4 типа из 5" % (t.get("kept"), len(t.get("types") or [])))
        if t and not t.get("schema_ok"):
            problems.append("tasks.json не проходит task.schema.json организаторов:\n    " + "\n    ".join(t["schema_errors"][:20]))
        if not rep["illustration_schema_ok"]:
            problems.append("illustrations.json не проходит illustration.schema.json организаторов:\n    " +
                            "\n    ".join(rep["illustration_schema_errors"][:20]))
        if rep["steps_without_illustration"]:
            problems.append("шаги без иллюстрации: " + ", ".join(rep["steps_without_illustration"][:10]))
        for p in problems:
            print("ОШИБКА СБОРКИ КУРСА: " + p, file=sys.stderr)
        sys.exit(1 if problems else 0)
